  var DICTS = { en: EN, ru: RU, uk: UK, es: ES };
  var order = ['en', 'ru', 'uk', 'es'];
  var current = 'en';

  function detect() {
    var q = /[?&]lang=([a-z]{2})/.exec(location.search);
    if (q && DICTS[q[1]]) { return q[1]; }
    var nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    for (var i = 0; i < order.length; i++) {
      if (nav.indexOf(order[i]) === 0) { return order[i]; }
    }
    return 'en';
  }

  function supports(lang) { return !!DICTS[lang]; }
  function use(lang) { current = DICTS[lang] ? lang : 'en'; return current; }
  function lang() { return current; }
  function next() { return use(order[(order.indexOf(current) + 1) % order.length]); }

  function t(key, params) {
    var dict = DICTS[current] || EN;
    var s = dict[key];
    if (s === undefined) { s = EN[key]; }
    if (s === undefined) { return key; }
    if (params) {
      for (var k in params) {
        if (params.hasOwnProperty(k)) {
          s = s.split('{' + k + '}').join(String(params[k]));
        }
      }
    }
    return s;
  }

  function list(key) { return t(key).split(','); }

  /* Some texts exist only for some cards, so callers have to be able to ask. */
  function has(key) {
    var dict = DICTS[current] || EN;
    return dict[key] !== undefined || EN[key] !== undefined;
  }

  return {
    t: t, has: has, list: list, use: use, lang: lang, next: next,
    detect: detect, supports: supports, languages: order
  };
